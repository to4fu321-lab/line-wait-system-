// お直し項目名 → 内容に合う絵文字を推測
//   一括取込（プリセット/OCR）で項目アイコンを自動付与するために使用。
//   キーワードは「具体的なもの順」に評価する（先勝ち）。
// ============================================================
const ICON_RULES: { kw: string[]; icon: string }[] = [
  { kw: ['刺繍', 'ネーム', '名前', '校章', 'ワッペン', 'マーク', '記名'], icon: '🧵' },
  { kw: ['ボタン'], icon: '🔘' },
  { kw: ['ホック', 'かぎホック', 'カギホック'], icon: '🪝' },
  { kw: ['ファスナー', 'チャック', 'ジッパー', 'ジップ'], icon: '🔗' },
  { kw: ['ゴム'], icon: '➰' },
  { kw: ['補修', '修理', '破れ', 'ほつれ', 'かけつぎ', '穴', 'ダメージ'], icon: '🩹' },
  { kw: ['交換', '取替', '取り替', '付け替', 'つけ替'], icon: '🔄' },
  { kw: ['ウエスト', '胴', 'ヒップ', 'わたり', 'ワタリ'], icon: '📐' },
  { kw: ['裾', '丈', '股下', '袖', 'パンツ', 'スカート丈'], icon: '📏' },
  { kw: ['肩', '身幅', '幅', '詰め', '出し', 'サイズ'], icon: '✂️' },
]

export function repairItemIcon(name: string): string {
  const n = (name ?? '').trim()
  for (const r of ICON_RULES) {
    if (r.kw.some(k => n.includes(k))) return r.icon
  }
  return '✂️'
}
